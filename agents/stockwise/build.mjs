// Bundles the StockWise agent definition (instructions, rules memory, schedules, skill files)
// into the agent-gateway edge function. Run after editing anything in agents/stockwise/:
//   node agents/stockwise/build.mjs
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "../../supabase/functions/agent-gateway/stockwise_def.ts");
const skillDir = join(here, "skills/pop-scoreboard");
const skillFiles = readdirSync(skillDir).sort().map((f) => f.endsWith(".ttf")
  ? { path: "pop-scoreboard/" + f, b64: readFileSync(join(skillDir, f)).toString("base64") }
  : { path: "pop-scoreboard/" + f, text: readFileSync(join(skillDir, f), "utf8") });
const ts = `// GENERATED by agents/stockwise/build.mjs from agents/stockwise/. Do not edit by hand.
export const INSTRUCTIONS = ${JSON.stringify(readFileSync(join(here, "instructions.md"), "utf8"))};
export const RULES_MD = ${JSON.stringify(readFileSync(join(here, "memory/rules.md"), "utf8"))};
export const SCHEDULES: { timezone: string; budget_usd_cents: string; runs: { label: string; name: string; cron: string; prompt: string }[] } = ${readFileSync(join(here, "schedules.json"), "utf8").trim()};
export const SKILL_FILES: { path: string; b64?: string; text?: string }[] = ${JSON.stringify(skillFiles, null, 1)};
`;
writeFileSync(out, ts);
console.log("wrote", out, ts.length, "bytes");
